"""Flashcard id ledger (audit P3-51, decision D13): content/card-ids.json keeps each lesson's card ids in order, so a card whose front text is
edited (its id is a hash of that text) keeps its review history.

Every build compares each lesson's cards with the ledger, position by position. When the card at a position has a new id and the old id is
gone from the lesson, the build records old -> new in `aliases` (chains collapse: a -> b, then b -> c gives a -> c) and ships the aliases whose
target still exists as manifest.cardAliases; GA.store moves state.cards[old] once. Cards that were reordered, or removed, only produce a
warning: no alias is guessed. Appending cards keeps the aliases of the positions before them. `build.py --check` reports, never writes.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

LEDGER = Path("content") / "card-ids.json"


def load(root: Path, errors: list[str]) -> dict:
    p = root / LEDGER
    if not p.exists():
        return {"lessons": {}, "aliases": {}}
    try:
        doc = json.loads(p.read_text())
    except ValueError as e:
        errors.append(f"{LEDGER}: not valid JSON ({e})")
        return {"lessons": {}, "aliases": {}}
    if not isinstance(doc.get("lessons"), dict) or not isinstance(doc.get("aliases", {}), dict):
        errors.append(f"{LEDGER}: needs \"lessons\" {{id: [card ids]}} and \"aliases\" {{old: new}}")
        return {"lessons": {}, "aliases": {}}
    return {"lessons": doc["lessons"], "aliases": dict(doc.get("aliases") or {})}


def update(ledger: dict, current: dict[str, list[str]], warnings: list[str]) -> tuple[dict, list[tuple[str, str]]]:
    """(the new ledger, the aliases this build adds). `current` = {lesson id: [card ids in order]}."""
    aliases = dict(ledger.get("aliases") or {})
    added: list[tuple[str, str]] = []
    old_lessons = ledger.get("lessons") or {}
    for lid, cur in current.items():
        old = old_lessons.get(lid)
        if old is None or old == cur:
            continue
        cur_set, old_set = set(cur), set(old)
        gone = [x for x in old if x not in cur_set]
        if not gone:
            if len(cur) > len(old) and cur[:len(old)] == old:
                continue                                                       # cards appended
            warnings.append(f"cards of {lid} were reordered or added in the middle: their ids are unchanged, nothing to carry over")
            continue
        n = min(len(old), len(cur))
        appended_only = len(cur) >= len(old) and all(x not in old_set for x in cur[len(old):])
        pairs = [(old[i], cur[i]) for i in range(n) if old[i] != cur[i] and old[i] not in cur_set and cur[i] not in old_set]
        if not appended_only or len(pairs) != len(gone) or any(old[i] != cur[i] and (old[i] in cur_set or cur[i] in old_set) for i in range(n)):
            warnings.append(f"cards of {lid}: {len(gone)} card(s) removed or moved ({', '.join(gone[:3])}): their review history is not carried "
                            "over (only a card edited in place keeps its history)")
            continue
        for a, b in pairs:
            added.append((a, b))
            for k, v in list(aliases.items()):
                if v == a:
                    aliases[k] = b
            aliases[a] = b
    # a lesson removed from the content keeps its ledger row (its cards may come back); new lessons are added as they are
    lessons = dict(old_lessons)
    lessons.update(current)
    aliases = {k: v for k, v in aliases.items() if k != v}
    return {"lessons": dict(sorted(lessons.items())), "aliases": dict(sorted(aliases.items()))}, added


def shipped(ledger: dict, card_ids: set[str]) -> dict[str, str]:
    """manifest.cardAliases: the ledger's aliases whose target is a current card and whose source is not (a source that is a card again
    must keep its own history)"""
    return {k: v for k, v in sorted((ledger.get("aliases") or {}).items()) if v in card_ids and k not in card_ids}


def save(root: Path, ledger: dict) -> bool:
    """write the ledger when it changed (atomic replace); True when written"""
    p = root / LEDGER
    body = json.dumps({"_comment": "Generated by build.py (audit P3-51): each lesson's flashcard ids in order, and old -> new ids of cards whose "
                       "front text was edited, so their review history follows them. Edit nothing here by hand.",
                       **ledger}, ensure_ascii=False, indent=1) + "\n"
    if p.exists() and p.read_text() == body:
        return False
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + f".tmp{os.getpid()}")
    tmp.write_text(body)
    os.replace(tmp, p)
    return True
